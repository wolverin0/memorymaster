"""Recognize generated envelopes without turning separated source spans into evidence."""

from __future__ import annotations

import re
from dataclasses import dataclass

GENERATED_OPENER = "<!-- generated by MemoryMaster; rebuild instead of editing -->"
GENERATED_CLOSER = "<!-- /generated by MemoryMaster -->"
GENERATED_MARKER = GENERATED_OPENER
_MARKER = re.compile(
    r"<!--[\s\ufeff]*(?P<close>/\s*)?generated\s+by\s+MemoryMaster\b[^>]*-->", re.I,
)


@dataclass(frozen=True)
class SourceSpan:
    start: int
    end: int
    text: str


@dataclass(frozen=True)
class GeneratedText:
    text: str
    spans: tuple[SourceSpan, ...]
    excluded_spans: tuple[tuple[int, int], ...] = ()


def contains_generated_marker(text: str) -> bool:
    return bool(_MARKER.search(text))


def strip_generated_spans(text: str) -> GeneratedText:
    """Keep original character offsets; unclosed/legacy envelopes own their suffix.

    ``text`` is a display convenience. Evidence consumers use ``spans`` rather
    than asserting that text across a removed range was one authored statement.
    Stray closers are excluded too, so they cannot survive as intake markers.
    """
    removed: list[tuple[int, int]] = []
    depth = 0
    start = 0
    for marker in _MARKER.finditer(text):
        if marker.group("close"):
            if depth:
                depth -= 1
                if depth == 0:
                    removed.append((start, marker.end()))
            else:
                removed.append(marker.span())
        else:
            if depth == 0:
                start = marker.start()
            depth += 1
    if depth:
        removed.append((start, len(text)))
    spans: list[SourceSpan] = []
    position = 0
    for start, end in removed:
        if position < start:
            spans.append(SourceSpan(position, start, text[position:start]))
        position = end
    if position < len(text):
        spans.append(SourceSpan(position, len(text), text[position:]))
    spans = [span for span in spans if span.text.strip("\ufeff \t\r\n")]
    return GeneratedText("\n".join(span.text for span in spans), tuple(spans), tuple(removed))
