def load_due_failures(path: Path) -> tuple[list[dict] | None, datetime | None]:
    """FAIL rows of the due-measurements file plus its mtime; (None, None) when missing/unreadable."""
    try:
        stat = Path(path).stat()
        if stat.st_size > BRIEF_MAX_DUE_BYTES:
            raise ValueError("due_measurements_size")
        data = json.loads(Path(path).read_bytes())
        rows = data["items"] if isinstance(data, dict) else data
        if not isinstance(rows, list):
            raise ValueError("due_measurements_shape")
    except (OSError, ValueError, KeyError, RecursionError):
        return None, None
    failures = []
    for row in rows:
        result = row.get("result") if isinstance(row, dict) else None
        if not (isinstance(result, str) and result.strip().startswith("FAIL") and isinstance(row.get("id"), str)):
            continue
        if not _safe({"id": row["id"], "result": result}):
            continue
        instant = None
        for name in ("done_at", "checked_at"):
            try:
                instant = _parse_iso_strict(name, row[name]) if isinstance(row.get(name), str) else None
            except ValueError:
                instant = None
            if instant:
                break
        failures.append({"id": _display(row["id"], 48), "when": instant, "text": _display(result, 110)})
    return failures, datetime.fromtimestamp(stat.st_mtime, timezone.utc)


ROADMAP_SECTIONS = ("Delivery-first program", "Lane backlog tracker", "Now")  # priority order
MAX_ROADMAP_BYTES = 2 * 1024 * 1024
_HEADING = re.compile(r"^(#{1,6})\s+(.*?)\s*#*\s*$")
_OPEN_ITEM = re.compile(r"^\s*[-*]\s+\[ \]\s+(\S.*)$")


def roadmap_next_item(project_root: Path) -> tuple[tuple[str, int] | None, datetime | None]:
    """First unchecked `- [ ]` item under the priority sections of <project_root>/ROADMAP.md.

    Returns ((text, 1-based line) | None, mtime); mtime is None when the file is missing or unreadable.
    A section runs from its heading to the next heading of equal or higher level, so `###` blocks
    inside `## Now` count. Heading match is the section name optionally followed by a non-word suffix.
    """
    path = Path(project_root) / "ROADMAP.md"
    try:
        if path.is_symlink() or not path.is_file() or path.stat().st_size > MAX_ROADMAP_BYTES:
            return None, None
        mtime = datetime.fromtimestamp(path.stat().st_mtime, timezone.utc)
        lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    except OSError:
        return None, None
    fenced = False
    headings: list[tuple[int, int, str]] = []  # (line index, level, title)
    items: list[tuple[int, str]] = []
    for index, line in enumerate(lines):
        if line.lstrip().startswith(("```", "~~~")):
            fenced = not fenced
        elif not fenced:
            heading, item = _HEADING.match(line), _OPEN_ITEM.match(line)
            if heading:
                headings.append((index, len(heading.group(1)), heading.group(2).strip()))
            elif item:
                items.append((index, item.group(1).strip()))
    for name in ROADMAP_SECTIONS:
        pattern = re.compile(re.escape(name) + r"(?!\w)", re.IGNORECASE)
        for position, (start, level, title) in enumerate(headings):
            if not pattern.match(title):
                continue
            end = next((h[0] for h in headings[position + 1:] if h[1] <= level), len(lines))
            found = next(((index, text) for index, text in items if start < index < end), None)
            if found:
                return (found[1], found[0] + 1), mtime
    return None, mtime


SECTION_KEYS = {
    "project_purpose": "Purpose",
    "purpose": "Purpose",
    "constraint": "Constraints",
    "rule": "Constraints",
    "invariant": "Constraints",
    "decision": "Decisions",
    "architecture_decision": "Decisions",
    "gotcha": "Gotchas",
    "pitfall": "Gotchas",
    "workaround": "Gotchas",
}


def _section(row: dict) -> str | None:
    return SECTION_KEYS.get(row.get("predicate")) or SECTION_KEYS.get(row.get("claim_type"))


def _claim_item(row: dict, citations: list[dict], *, now: datetime | None = None) -> dict | None:
    if (
        row.get("status") != "confirmed"
        or (row.get("visibility") or "public") != "public"
        or row.get("replaced_by_claim_id") is not None
        or row.get("source_agent") in GENERATED_SOURCES
        or not citations
        or not _section(row)
    ):
        return None
    relevant = {
        name: row.get(name)
        for name in (
            "text",
            "subject",
            "predicate",
            "object_value",
            "claim_type",
            "status",
            "visibility",
            "replaced_by_claim_id",
            "source_agent",
            "valid_from",
            "valid_until",
            "scope",
            "tenant_id",
            "event_time",
            "created_at",
            "pinned",
        )
    }
    if not _safe(relevant) or not all(_safe(citation) for citation in citations):
        return None
    if not claim_is_temporally_current(
        SimpleNamespace(valid_from=row.get("valid_from"), valid_until=row.get("valid_until")), now=now
    ):
        return None
    if not str(row.get("text") or "").strip():
        return None
    if not all(citation.get("source") and citation.get("locator") for citation in citations):
        return None
    support = {
        "kind": "claim",
        "id": int(row["id"]),
        "version": int(row.get("version") or 1),
        "hash": digest(relevant),
        "citations": [{"id": int(c["id"]), "hash": digest(c)} for c in citations],
    }
    section = _section(row)
    date_field = "event_time" if row.get("event_time") else "created_at"
    raw_date = row.get(date_field)
    date = None
    if isinstance(raw_date, str):
        try:
            date = _parse_iso_strict(date_field, raw_date)
        except ValueError:
            pass  # Keep cited prose, explicitly omit malformed persisted dates.
    text = row["text"]
    if section == "Decisions" and date is not None:
        label = "event" if date_field == "event_time" else "recorded"
        text = f"{date.date().isoformat()} ({label}): {text}"
    # Egress and inert-line formatting cover the entire composed display,
    # including date metadata, rather than only the source prose.
    text = _display(text)
    # Exact UTC microseconds compare instants without converting to a calendar
    # date that can overflow at year 1/9999 with a nonzero offset. Missing dates
    # sort before every valid instant (ISO offsets are strictly below 24 hours).
    instant_key = -86_400_000_000
    if date is not None:
        elapsed = date - datetime.min.replace(tzinfo=timezone.utc)
        instant_key = (elapsed.days * 86400 + elapsed.seconds) * 1_000_000 + elapsed.microseconds
    return {
        "key": f"claim:{row['id']}",
        "section": section,
        "text": text,
        "support": support,
        "pinned": bool(row.get("pinned")),
        "sort": [0 if row.get("pinned") else 1, instant_key, int(row["id"])],
    }


def _read_claims(
    config: Any,
    *,
    ids: list[int] | None = None,
    changed_since: str | None = None,
    validation: bool = False,
    max_seen_id: int | None = None,
    prior_fence: dict | None = None,
    as_of: datetime | None = None,
) -> tuple[dict, bool, dict]:
    # One instant governs eligibility and all temporal fence comparisons,
    # including when a boundary is crossed while SQLite rows are collected.
    as_of = as_of or datetime.fromisoformat(utc_now().replace("Z", "+00:00"))
    limit = 64 if validation else MAX_CLAIMS
    citation_limit = 256 if validation else MAX_CITATIONS
    byte_limit = 2 * 1024 * 1024 if validation else MAX_SOURCE_BYTES
    if ids is not None and len(ids) > MAX_CLAIMS:
        raise ValueError("claim_limit")
    deadline = time.monotonic() + 0.1
    with closing(
        sqlite3.connect(Path(config.db_path).resolve().as_uri() + "?mode=ro", uri=True, timeout=0.025)
    ) as conn:
        conn.row_factory = sqlite3.Row
        conn.execute("PRAGMA query_only=ON")
        conn.set_progress_handler(lambda: int(time.monotonic() > deadline), 1000)
        conn.execute("BEGIN")
        try:
            clock = conn.execute("SELECT epoch,seq FROM project_source_clock WHERE singleton=1").fetchone()
            source_cursor = {"epoch": clock[0], "seq": clock[1]} if clock else None
        except sqlite3.OperationalError:
            source_cursor = None
        scopes = (config.scope, *config.aliases)
        params: list[Any] = [config.tenant_id, *scopes]
        where = "tenant_id IS ? AND scope IN (" + ",".join("?" for _ in scopes) + ")"
        changed_ids = []
        temporal_boundaries = []
        if changed_since:
            cursor = (prior_fence or {}).get("source_cursor")
            if (not source_cursor or not isinstance(cursor, dict)
                    or cursor.get("epoch") != source_cursor["epoch"]
                    or type(cursor.get("seq")) is not int
                    or not 0 <= cursor["seq"] <= source_cursor["seq"]):
                raise ValueError("incremental_cursor_unavailable")
            # The transactional cursor covers every insert as well as late
            # commits, deletes, scope moves and citation edits. Do not also scan
            # IDs above the project's max_seen_id: unchanged unrelated projects
            # can have higher IDs and would be traversed again on every start.
            instant = datetime.fromisoformat(changed_since.replace("Z", "+00:00"))
            if instant.tzinfo is None:
                raise ValueError("unqualified_baseline_time")
            if instant > as_of:
                raise ValueError("future_baseline_time")
            watched = (prior_fence or {}).get("watched_ids", [])
            if len(watched) > MAX_CLAIMS or any(type(id) is not int or id <= 0 for id in watched):
                raise ValueError("invalid_scan_fence")
            watched_set = set(watched)
            watched_sql = ",".join("?" for _ in watched) or "NULL"
            # Protected continuity metadata holds future boundaries ordered by
            # integer instants, including bounds beyond the UTC calendar.
            # Never reload every watched row to compare ISO forms.
            # Older fences lack this contract and must fail closed for rebuild.
            temporal_boundaries = (prior_fence or {}).get("temporal_boundaries")
            if ((prior_fence or {}).get("temporal_version") != 2
                    or not isinstance(temporal_boundaries, list)
                    or len(temporal_boundaries) > 2 * MAX_CLAIMS
                    or any(not isinstance(entry, list) or len(entry) != 2
                           or not isinstance(entry[0], str)
                           or type(entry[1]) is not int or entry[1] not in watched_set
                           for entry in temporal_boundaries)
                    or temporal_boundaries != sorted(temporal_boundaries, key=_boundary_key)):
                raise ValueError("incremental_temporal_fence_unavailable")
            lower = bisect_left(temporal_boundaries, _instant_key(instant),
                                key=lambda entry: _boundary_key(entry)[0])
            upper = bisect_right(temporal_boundaries, _instant_key(as_of),
                                 key=lambda entry: _boundary_key(entry)[0])
            temporal_ids = sorted({id for _, id in temporal_boundaries[lower:upper]})
            temporal_boundaries = temporal_boundaries[upper:]
            queries = [
                "SELECT changes.claim_id AS id FROM project_source_changes changes "
                "INDEXED BY idx_project_source_changes_seq "
                "LEFT JOIN claims ON claims.id=changes.claim_id "
                f"WHERE changes.seq > ? AND changes.seq <= ? AND (({where}) "
                f"OR changes.claim_id IN ({watched_sql}))",
            ]
            changes_params: list[Any] = [cursor["seq"], source_cursor["seq"], *params, *watched]
            if temporal_ids:
                queries.append("SELECT id FROM claims NOT INDEXED WHERE id IN ("
                               + ",".join("?" for _ in temporal_ids) + ")")
                changes_params.extend(temporal_ids)
            changed_ids = [row[0] for row in conn.execute(
                "SELECT id FROM (" + " UNION ".join(queries) + ") ORDER BY id LIMIT ?",
                [*changes_params, limit + 1],
            )]
            if len(changed_ids) > limit:
                return {}, False, {}
            ids = sorted(set(ids or ()) | set(changed_ids))
        if ids is not None:
            # An empty IN set reads neither claim payloads nor citations.
            where += " AND id IN (" + (",".join("?" for _ in ids) or "NULL") + ")"
            params.extend(ids)
        # Builder scans watch bounded all-status IDs. Ineligible rows can become
        # eligible without a reliable post-commit timestamp; their IDs are only
        # protected continuity metadata, never factual support or public output.
        fields = [row[1] for row in conn.execute("PRAGMA table_info(claims)")]
        names = [
            name
            for name in fields
            if name
            in {
                "id",
                "version",
                "text",
                "subject",
                "predicate",
                "object_value",
                "claim_type",
                "status",
                "visibility",
                "replaced_by_claim_id",
                "source_agent",
                "valid_from",
                "valid_until",
                "scope",
                "tenant_id",
                "event_time",
                "created_at",
                "updated_at",
                "pinned",
            }
        ]
        claim_table = "claims NOT INDEXED" if ids is not None else "claims"
        if (ids is None and getattr(config, "brief", False)
                and {"status", "visibility", "replaced_by_claim_id", "predicate", "claim_type"} <= set(fields)):
            # Builder scan with the brief on (T-2278): read only rows that can render. The change cursor reports
            # a candidate that is later confirmed, so ineligible rows need no watching and the 512 cap bounds what
            # a project can show instead of how big its scope is. Brief off keeps the all-status fence unchanged.
            marks = ",".join("?" for _ in SECTION_KEYS)
            where += (" AND status='confirmed' AND COALESCE(visibility,'public')='public'"
                      f" AND replaced_by_claim_id IS NULL AND (predicate IN ({marks}) OR claim_type IN ({marks}))")
            params.extend([*SECTION_KEYS, *SECTION_KEYS])
            claim_table = "claims" + pinned_scope_index(conn)
        # Reject oversized rows before materializing their payload in Python.
        size = "+".join(f"length(CAST(COALESCE({name},'') AS BLOB))" for name in names)
        columns = ",".join(
            f"CASE WHEN ({size}) <= {MAX_FIELD_BYTES} THEN {name} ELSE NULL END AS {name}" if name != "id" else name
            for name in names
        )
        cursor = conn.execute(
            f"SELECT {columns}, ({size}) AS _source_bytes FROM {claim_table} WHERE {where} ORDER BY id LIMIT ?",
            [*params, limit + 1],
        )
        rows = []
        total = 0
        for row in cursor:
            if len(rows) >= limit:
                fingerprint = {"source_bytes": total}
                if not validation:
                    watched = sorted(set((prior_fence or {}).get("watched_ids", ()))
                                     | set(ids or ()) | {int(value["id"]) for value in rows})
                    fingerprint["scan_fence"] = {
                        "kind": "scan_fence",
                        "watched_ids": watched[:MAX_CLAIMS],
                        "max_seen_id": max([max_seen_id or 0, *watched]),
                        "complete": False,
                    }
                return {}, False, fingerprint
            row_bytes = len(json.dumps(dict(row)).encode())
            if total + row_bytes > byte_limit:
                # Exhaust the shared source allowance so ledger reads cannot
                # restart that budget after an interrupted SQLite stream.
                return {}, False, {"source_bytes": byte_limit}
            total += row_bytes
            rows.append(row)
        complete = True
        oversized = {row["id"] for row in rows if row["_source_bytes"] > MAX_FIELD_BYTES}
        complete = complete and not oversized
        ids_read = [row["id"] for row in rows]
        citations: dict[int, list] = {}
        if ids_read:
            placeholders = ",".join("?" for _ in ids_read)
            citation_index = " INDEXED BY idx_project_citations_claim" if source_cursor else ""
            citation_size = "length(CAST(COALESCE(source,'')||COALESCE(locator,'')||COALESCE(excerpt,'') AS BLOB))"
            citation_cursor = conn.execute(
                "SELECT id,claim_id,"
                + ",".join(
                    f"CASE WHEN {citation_size} <= {MAX_FIELD_BYTES} THEN {name} ELSE NULL END AS {name}"
                    for name in ("source", "locator", "excerpt")
                )
                + f",{citation_size} AS _source_bytes "
                f"FROM citations{citation_index} WHERE claim_id IN ({placeholders}) ORDER BY id LIMIT ?",
                [*ids_read, citation_limit + 1],
            )
            for index, citation in enumerate(citation_cursor):
                citation_bytes = len(json.dumps(dict(citation)).encode())
                if total + citation_bytes > byte_limit:
                    return {}, False, {"source_bytes": byte_limit}
                total += citation_bytes
                if index >= citation_limit:
                    return {}, False, {"source_bytes": total}
                if citation["_source_bytes"] > MAX_FIELD_BYTES:
                    oversized.add(citation["claim_id"])
                    complete = False
                value = dict(citation)
                value.pop("_source_bytes")
                citations.setdefault(citation["claim_id"], []).append(value)
        items = {}
        for row in rows:
            if row["id"] in oversized:
                continue
            item = _claim_item(dict(row), citations.get(row["id"], []), now=as_of)
            if item:
                items[item["key"]] = item
        # Refresh normalized metadata only for source rows materialized because
        # they changed, crossed a boundary or were explicitly requested.
        refreshed_ids = set(changed_ids) | set(ids_read)
        temporal_boundaries = sorted([
            *[entry for entry in temporal_boundaries if entry[1] not in refreshed_ids],
            *[[boundary.isoformat(timespec="microseconds"), id] for id, boundary in _validity_instants(rows)
              if _instant_key(boundary) > _instant_key(as_of)],
        ], key=_boundary_key)
        fingerprint = {
            "data_version": conn.execute("PRAGMA data_version").fetchone()[0],
            "next_temporal_boundary": (datetime.fromisoformat(temporal_boundaries[0][0]).isoformat()
                                       if temporal_boundaries else None),
            "source_bytes": total,
            "changed_ids": changed_ids,
        }
        if not validation:
            watched_ids = sorted(set((prior_fence or {}).get("watched_ids", ()))
                                 | set(ids or ()) | {int(row["id"]) for row in rows})
            fingerprint["scan_fence"] = {
                "kind": "scan_fence",
                "watched_ids": watched_ids[:MAX_CLAIMS],
                "max_seen_id": max([max_seen_id or 0, *watched_ids]),
                "complete": complete and len(watched_ids) <= MAX_CLAIMS and source_cursor is not None,
                "source_cursor": source_cursor,
                "temporal_version": 2,
                "temporal_boundaries": temporal_boundaries,
            }
            complete = complete and len(watched_ids) <= MAX_CLAIMS
        return items, complete, fingerprint


def snapshot_since(config: Any, coverage: dict, read_at: str) -> dict:
    return load_project_snapshot(config, coverage=coverage, changed_since=read_at)


def load_project_snapshot(
    config: Any,
    *,
    coverage: dict | None = None,
    changed_since: str | None = None,
    claim_ids: list[int] | None = None,
    validation: bool = False,
) -> dict:
    result: dict[str, Any] = {
        "read_at": utc_now(),
        "coverage": {},
        "items": {},
        "complete": False,
        "diagnostics": [],
        "fingerprints": {},
        "next_temporal_boundary": None,
    }
    if not config.enabled:
        result["diagnostics"] = ["inactive"]
        return result
    try:
        ids = claim_ids
        prior_fence = None
        if coverage is not None:
            if not changed_since:
                raise ValueError("incremental_read_time_unavailable")
            prior_fence = coverage.get("__scan_fence__")
            # Coverage already holds unchanged support hashes. Only explicit
            # display supports and indexed changes need source materialization.
            ids = claim_ids or []
        items, complete, fingerprints = _read_claims(
            config,
            ids=ids,
            changed_since=changed_since,
            validation=validation,
            max_seen_id=prior_fence.get("max_seen_id") if isinstance(prior_fence, dict) else None,
            prior_fence=prior_fence,
            as_of=datetime.fromisoformat(result["read_at"].replace("Z", "+00:00")),
        )
        if coverage is not None and (not prior_fence or not prior_fence.get("complete")):
            complete = False
            result["diagnostics"].append("incremental_scan_fence_incomplete")
    except (sqlite3.Error, OSError, ValueError, TypeError):
        items, complete, fingerprints = {}, False, {}
        result["diagnostics"].append("claims_unavailable")
    byte_budget = 2 * 1024 * 1024 if validation else MAX_SOURCE_BYTES
    cards, ledger_complete, diagnostics = load_ledger(
        config, max_bytes=max(0, byte_budget - int(fingerprints.get("source_bytes", 0)))
    )
    items.update((card["key"], card) for card in cards.values())
    result.update(items=items, complete=complete and ledger_complete, fingerprints=fingerprints)
    result["next_temporal_boundary"] = fingerprints.get("next_temporal_boundary")
    carried = {key: value for key, value in (coverage or {}).items() if key.startswith("claim:")}
    for id in fingerprints.pop("changed_ids", []):
        carried.pop(f"claim:{id}", None)
    result["coverage"] = {**carried, **{
        key: item["support"] for key, item in items.items() if item.get("open", True)
    }}
    fence = fingerprints.pop("scan_fence", None)
    if fence is not None:
        fence["complete"] = fence["complete"] and complete
        result["coverage"]["__scan_fence__"] = fence
    result["diagnostics"].extend(diagnostics)
    if len(json.dumps(result["coverage"]).encode()) > 128 * 1024:
        result.update(coverage={}, complete=False)
        result["diagnostics"].append("coverage_limit")
    return result


def load_confirmed_project_claims(config: Any) -> list[dict]:
    snapshot = load_project_snapshot(config)
    return [item for key, item in snapshot["items"].items() if key.startswith("claim:")]
