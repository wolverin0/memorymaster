"""Bounded read-only project evidence, never a writable profile repository."""

from __future__ import annotations

from contextlib import closing
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import re
import sqlite3
import time
from types import SimpleNamespace
from typing import Any

from memorymaster.core.security import scan_persisted_value
from memorymaster.core.temporal_policy import claim_is_temporally_current
from memorymaster.profile.egress import prepare_claim_egress

OPEN_STATES = frozenset({"queued", "ready", "running", "review", "blocked"})
MAX_CLAIMS = 512
MAX_CITATIONS = 2048
MAX_FIELD_BYTES = 16384
MAX_SOURCE_BYTES = 8 * 1024 * 1024
GENERATED_SOURCES = frozenset(
    {"project-projection", "compiled-profile", "cockpit", "operational-review", "beat-narrative", "graph-summary"}
)


def digest(value: Any) -> str:
    return hashlib.sha256(
        json.dumps(value, sort_keys=True, ensure_ascii=False, separators=(",", ":")).encode()
    ).hexdigest()


def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat()


def _safe(value: Any) -> bool:
    text = json.dumps(value, ensure_ascii=False)
    lowered = text.lower()
    return (
        len(text.encode()) <= MAX_FIELD_BYTES
        and not any(marker in lowered for marker in ("generated by memorymaster", "[redacted", "[erased_claim_text]"))
        and not scan_persisted_value(value)
        and not prepare_claim_egress(text).blocked
    )


def _display(text: Any, limit: int = 240) -> str:
    # One inert line; never permit source headings or markers to create instructions.
    text = prepare_claim_egress(str(text or "")).text
    text = re.sub(r"[\x00-\x1f\x7f]", " ", text)
    text = text.translate(str.maketrans({"<": "‹", ">": "›", "[": "（", "]": "）", "`": "′"}))
    literal = " ".join(text.split())
    return literal if len(literal) <= limit else literal[: limit - 1] + "…"


def cheap_fingerprints(config: Any) -> dict[str, Any]:
    """Filesystem change hints only: callers must also honor temporal boundaries."""
    if not config.enabled:
        return {}
    paths = [Path(config.db_path), Path(str(config.db_path) + "-wal")]
    if config.ledger_root:
        paths.extend(_ledger_paths(config))
    result: dict[str, Any] = {}
    for index, path in enumerate(paths):
        try:
            stat = path.stat()
            result[str(index)] = [stat.st_mtime_ns, stat.st_size]
        except OSError:
            result[str(index)] = None
    return result


def _ledger_paths(config: Any) -> list[Path]:
    root = Path(config.ledger_root)
    if root.is_file():
        return [root]
    # Enumerate only the explicit approved input directory, with a hard count cap.
    paths = []
    for path in root.iterdir():
        if path.suffix == ".json" and path.is_file():
            paths.append(path)
            if len(paths) > 1024:
                raise ValueError("ledger_file_limit")
    return sorted(paths)


def load_ledger(config: Any, *, max_bytes: int = MAX_SOURCE_BYTES) -> tuple[dict, bool, list[str]]:
    if not config.ledger_root or not config.ledger_repo or not config.ledger_filtered:
        return {}, False, ["ledger_unavailable"]
    consumed = 0

    def read_bytes(path: Path) -> bytes:
        nonlocal consumed
        remaining = max_bytes - consumed
        if remaining < 0:
            raise ValueError("ledger_byte_limit")
        with path.open("rb") as stream:
            raw = stream.read(remaining + 1)
        consumed += len(raw)
        if consumed > max_bytes:
            raise ValueError("ledger_byte_limit")
        return raw

    for attempt in range(2):
        try:
            paths = _ledger_paths(config)
            if not paths:
                raise ValueError("no_ledger_input")
            before = [(path.stat().st_mtime_ns, path.stat().st_size) for path in paths]
            if sum(size for _, size in before) > max_bytes:
                raise ValueError("ledger_byte_limit")
            records = []
            complete = True
            content_hashes = []
            for path in paths:
                raw = read_bytes(path)
                content_hashes.append(hashlib.sha256(raw).digest())
                data = json.loads(raw)
                if isinstance(data, dict) and "tasks" in data:
                    complete = complete and data.get("complete") is True
                    tasks = data["tasks"]
                else:
                    tasks = data if isinstance(data, list) else [data]
                if not isinstance(tasks, list):
                    raise ValueError("invalid_ledger")
                records.extend(tasks)
                if len(records) > 1024:
                    raise ValueError("ledger_record_limit")
            cards = {}
            for row in records:
                if not isinstance(row, dict):
                    raise ValueError("invalid_ledger_record")
                if row.get("repo") != config.ledger_repo:
                    continue
                if row.get("blind") or row.get("is_blind") or row.get("visibility", "public") != "public":
                    continue
                selected = {name: row.get(name) for name in ("id", "repo", "state", "title", "version")}
                if not all(
                    isinstance(selected[name], str) and selected[name].strip()
                    for name in ("id", "repo", "state", "title")
                ) or not _safe(selected):
                    complete = False
                    continue
                card_id = selected["id"]
                if card_id in cards:
                    raise ValueError("duplicate_card")
                support = {
                    "kind": "card",
                    "id": card_id,
                    "hash": digest(selected),
                    "version": selected["version"],
                    "state": selected["state"],
                }
                cards[card_id] = {
                    "key": "card:" + card_id,
                    "section": "Open cards",
                    "text": f"{_display(card_id, 48)} [{_display(selected['state'], 24)}] {_display(selected['title'], 80)}",
                    "support": support,
                    "open": selected["state"] in OPEN_STATES,
                    "sort": [selected["state"], card_id],
                }
                if len(cards) > 256:
                    raise ValueError("ledger_card_limit")
            after_hashes = [hashlib.sha256(read_bytes(path)).digest() for path in paths]
            after = [(path.stat().st_mtime_ns, path.stat().st_size) for path in paths]
            if before != after or content_hashes != after_hashes or paths != _ledger_paths(config):
                if attempt == 0:
                    continue
                raise ValueError("ledger_changed_during_read")
            return cards, complete, [] if complete else ["ledger_incomplete"]
        except (OSError, ValueError, TypeError, KeyError):
            return {}, False, ["ledger_unavailable"]
    return {}, False, ["ledger_unavailable"]


def _section(row: dict) -> str | None:
    mapping = {
        "project_purpose": "Purpose",
        "purpose": "Purpose",
        "constraint": "Constraints",
        "rule": "Constraints",
        "invariant": "Constraints",
        "decision": "Decisions",
        "architecture_decision": "Decisions",
        "gotcha": "Gotchas",
        "pitfall": "Gotchas",
        "workaround": "Gotchas",
    }
    return mapping.get(row.get("predicate")) or mapping.get(row.get("claim_type"))


def _claim_item(row: dict, citations: list[dict]) -> dict | None:
    if (
        row.get("status") != "confirmed"
        or (row.get("visibility") or "public") != "public"
        or row.get("replaced_by_claim_id") is not None
        or row.get("source_agent") in GENERATED_SOURCES
        or not citations
        or not _section(row)
    ):
        return None
    relevant = {
        name: row.get(name)
        for name in (
            "text",
            "subject",
            "predicate",
            "object_value",
            "claim_type",
            "status",
            "visibility",
            "replaced_by_claim_id",
            "source_agent",
            "valid_from",
            "valid_until",
            "scope",
            "tenant_id",
            "event_time",
            "created_at",
            "pinned",
        )
    }
    if not _safe(relevant) or not all(_safe(citation) for citation in citations):
        return None
    if not claim_is_temporally_current(
        SimpleNamespace(valid_from=row.get("valid_from"), valid_until=row.get("valid_until"))
    ):
        return None
    if not str(row.get("text") or "").strip():
        return None
    if not all(citation.get("source") and citation.get("locator") for citation in citations):
        return None
    support = {
        "kind": "claim",
        "id": int(row["id"]),
        "version": int(row.get("version") or 1),
        "hash": digest(relevant),
        "citations": [{"id": int(c["id"]), "hash": digest(c)} for c in citations],
    }
    section = _section(row)
    date = row.get("event_time") or row.get("created_at") or ""
    text = _display(row["text"])
    if section == "Decisions":
        label = "event" if row.get("event_time") else "recorded"
        text = f"{str(date)[:10]} ({label}): {text}"
    return {
        "key": f"claim:{row['id']}",
        "section": section,
        "text": text,
        "support": support,
        "pinned": bool(row.get("pinned")),
        "sort": [0 if row.get("pinned") else 1, str(date), int(row["id"])],
    }


def _read_claims(
    config: Any,
    *,
    ids: list[int] | None = None,
    changed_since: str | None = None,
    validation: bool = False,
    max_seen_id: int | None = None,
) -> tuple[dict, bool, dict]:
    limit = 64 if validation else MAX_CLAIMS
    citation_limit = 256 if validation else MAX_CITATIONS
    byte_limit = 2 * 1024 * 1024 if validation else MAX_SOURCE_BYTES
    if ids is not None and len(ids) > MAX_CLAIMS:
        raise ValueError("claim_limit")
    deadline = time.monotonic() + 0.1
    with closing(
        sqlite3.connect(Path(config.db_path).resolve().as_uri() + "?mode=ro", uri=True, timeout=0.025)
    ) as conn:
        conn.row_factory = sqlite3.Row
        conn.execute("PRAGMA query_only=ON")
        conn.set_progress_handler(lambda: int(time.monotonic() > deadline), 1000)
        conn.execute("BEGIN")
        scopes = (config.scope, *config.aliases)
        params: list[Any] = [config.tenant_id, *scopes]
        where = "tenant_id IS ? AND scope IN (" + ",".join("?" for _ in scopes) + ")"
        if ids is not None:
            clauses = []
            if ids:
                clauses.append("id IN (" + ",".join("?" for _ in ids) + ")")
                params.extend(ids)
            if changed_since:
                # Store writes use whole UTC seconds; read_at retains microseconds.
                # A bare second prefix includes every same-second timestamp suffix.
                instant = datetime.fromisoformat(changed_since.replace("Z", "+00:00"))
                if instant.tzinfo is None:
                    raise ValueError("unqualified_baseline_time")
                lower_bound = instant.astimezone(timezone.utc).strftime("%Y-%m-%dT%H:%M:%S")
                clauses.extend(
                    [
                        "updated_at >= ?",
                        "valid_from >= ?",
                        "EXISTS (SELECT 1 FROM citations c WHERE c.claim_id=claims.id AND c.created_at >= ?)",
                    ]
                )
                params.extend([lower_bound] * 3)
            if max_seen_id is not None:
                clauses.append("id > ?")
                params.append(max_seen_id)
            if not clauses:
                return {}, True, {"data_version": conn.execute("PRAGMA data_version").fetchone()[0]}
            where += " AND (" + " OR ".join(clauses) + ")"
        # Builder scans watch bounded all-status IDs. Ineligible rows can become
        # eligible without a reliable post-commit timestamp; their IDs are only
        # protected continuity metadata, never factual support or public output.
        fields = [row[1] for row in conn.execute("PRAGMA table_info(claims)")]
        names = [
            name
            for name in fields
            if name
            in {
                "id",
                "version",
                "text",
                "subject",
                "predicate",
                "object_value",
                "claim_type",
                "status",
                "visibility",
                "replaced_by_claim_id",
                "source_agent",
                "valid_from",
                "valid_until",
                "scope",
                "tenant_id",
                "event_time",
                "created_at",
                "updated_at",
                "pinned",
            }
        ]
        # Reject oversized rows before materializing their payload in Python.
        size = "+".join(f"length(CAST(COALESCE({name},'') AS BLOB))" for name in names)
        columns = ",".join(
            f"CASE WHEN ({size}) <= {MAX_FIELD_BYTES} THEN {name} ELSE NULL END AS {name}" if name != "id" else name
            for name in names
        )
        cursor = conn.execute(
            f"SELECT {columns}, ({size}) AS _source_bytes FROM claims WHERE {where} ORDER BY id LIMIT ?",
            [*params, limit + 1],
        )
        rows = []
        total = 0
        for row in cursor:
            if len(rows) >= limit:
                fingerprint = {"source_bytes": total}
                if not validation:
                    watched = sorted(set(ids or ()) | {int(value["id"]) for value in rows})
                    fingerprint["scan_fence"] = {
                        "kind": "scan_fence",
                        "watched_ids": watched[:MAX_CLAIMS],
                        "max_seen_id": max([max_seen_id or 0, *watched]),
                        "complete": False,
                    }
                return {}, False, fingerprint
            row_bytes = len(json.dumps(dict(row)).encode())
            if total + row_bytes > byte_limit:
                # Exhaust the shared source allowance so ledger reads cannot
                # restart that budget after an interrupted SQLite stream.
                return {}, False, {"source_bytes": byte_limit}
            total += row_bytes
            rows.append(row)
        complete = True
        oversized = {row["id"] for row in rows if row["_source_bytes"] > MAX_FIELD_BYTES}
        complete = complete and not oversized
        ids_read = [row["id"] for row in rows]
        citations: dict[int, list] = {}
        if ids_read:
            placeholders = ",".join("?" for _ in ids_read)
            citation_size = "length(CAST(COALESCE(source,'')||COALESCE(locator,'')||COALESCE(excerpt,'') AS BLOB))"
            citation_cursor = conn.execute(
                "SELECT id,claim_id,"
                + ",".join(
                    f"CASE WHEN {citation_size} <= {MAX_FIELD_BYTES} THEN {name} ELSE NULL END AS {name}"
                    for name in ("source", "locator", "excerpt")
                )
                + f",{citation_size} AS _source_bytes "
                f"FROM citations WHERE claim_id IN ({placeholders}) ORDER BY id LIMIT ?",
                [*ids_read, citation_limit + 1],
            )
            for index, citation in enumerate(citation_cursor):
                citation_bytes = len(json.dumps(dict(citation)).encode())
                if total + citation_bytes > byte_limit:
                    return {}, False, {"source_bytes": byte_limit}
                total += citation_bytes
                if index >= citation_limit:
                    return {}, False, {"source_bytes": total}
                if citation["_source_bytes"] > MAX_FIELD_BYTES:
                    oversized.add(citation["claim_id"])
                    complete = False
                value = dict(citation)
                value.pop("_source_bytes")
                citations.setdefault(citation["claim_id"], []).append(value)
        items = {}
        for row in rows:
            if row["id"] in oversized:
                continue
            item = _claim_item(dict(row), citations.get(row["id"], []))
            if item:
                items[item["key"]] = item
        now = utc_now()
        boundaries = [
            str(row[name])
            for row in rows
            for name in ("valid_from", "valid_until")
            if row[name] and str(row[name]) > now
        ]
        fingerprint = {
            "data_version": conn.execute("PRAGMA data_version").fetchone()[0],
            "next_temporal_boundary": min(boundaries) if boundaries else None,
            "source_bytes": total,
        }
        if not validation:
            watched_ids = sorted(set(ids or ()) | {int(row["id"]) for row in rows})
            fingerprint["scan_fence"] = {
                "kind": "scan_fence",
                "watched_ids": watched_ids[:MAX_CLAIMS],
                "max_seen_id": max([max_seen_id or 0, *watched_ids]),
                "complete": complete and len(watched_ids) <= MAX_CLAIMS,
            }
            complete = complete and len(watched_ids) <= MAX_CLAIMS
        return items, complete, fingerprint


def snapshot_since(config: Any, coverage: dict, read_at: str) -> dict:
    return load_project_snapshot(config, coverage=coverage, changed_since=read_at)


def load_project_snapshot(
    config: Any,
    *,
    coverage: dict | None = None,
    changed_since: str | None = None,
    claim_ids: list[int] | None = None,
    validation: bool = False,
) -> dict:
    result: dict[str, Any] = {
        "read_at": utc_now(),
        "coverage": {},
        "items": {},
        "complete": False,
        "diagnostics": [],
        "fingerprints": {},
        "next_temporal_boundary": None,
    }
    if not config.enabled:
        result["diagnostics"] = ["inactive"]
        return result
    try:
        ids = claim_ids
        prior_fence = None
        if coverage is not None:
            prior_fence = coverage.get("__scan_fence__")
            ids = sorted(
                set(int(key.split(":", 1)[1]) for key in coverage if key.startswith("claim:"))
                | set(prior_fence.get("watched_ids", ()) if isinstance(prior_fence, dict) else ())
            )
            if any(type(id) is not int or id <= 0 for id in ids):
                raise ValueError("invalid_scan_fence")
        items, complete, fingerprints = _read_claims(
            config,
            ids=ids,
            changed_since=changed_since,
            validation=validation,
            max_seen_id=prior_fence.get("max_seen_id") if isinstance(prior_fence, dict) else None,
        )
        if coverage is not None and (not prior_fence or not prior_fence.get("complete")):
            complete = False
            result["diagnostics"].append("incremental_scan_fence_incomplete")
    except (sqlite3.Error, OSError, ValueError, TypeError):
        items, complete, fingerprints = {}, False, {}
        result["diagnostics"].append("claims_unavailable")
    byte_budget = 2 * 1024 * 1024 if validation else MAX_SOURCE_BYTES
    cards, ledger_complete, diagnostics = load_ledger(
        config, max_bytes=max(0, byte_budget - int(fingerprints.get("source_bytes", 0)))
    )
    items.update((card["key"], card) for card in cards.values())
    result.update(items=items, complete=complete and ledger_complete, fingerprints=fingerprints)
    result["next_temporal_boundary"] = fingerprints.get("next_temporal_boundary")
    result["coverage"] = {key: item["support"] for key, item in items.items() if item.get("open", True)}
    fence = fingerprints.pop("scan_fence", None)
    if fence is not None:
        fence["complete"] = fence["complete"] and complete
        result["coverage"]["__scan_fence__"] = fence
    result["diagnostics"].extend(diagnostics)
    if len(json.dumps(result["coverage"]).encode()) > 128 * 1024:
        result.update(coverage={}, complete=False)
        result["diagnostics"].append("coverage_limit")
    return result


def load_confirmed_project_claims(config: Any) -> list[dict]:
    snapshot = load_project_snapshot(config)
    return [item for key, item in snapshot["items"].items() if key.startswith("claim:")]
