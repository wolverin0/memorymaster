"""Exclude generated memory context before capture persistence or provider egress."""

from __future__ import annotations

import re
from dataclasses import dataclass
from typing import Any, MutableMapping


@dataclass(frozen=True)
class SourceSpan:
    start: int
    end: int
    text: str


@dataclass(frozen=True)
class SanitizedTurn:
    text: str
    spans: tuple[SourceSpan, ...] = ()
    exclusion_reasons: tuple[str, ...] = ()
    contaminated: bool = False


_CITATION = re.compile(r"\bmm-[0-9a-f]{6,}(?:[-_][0-9a-z]+)*\b", re.I)
_GENERATED = re.compile(
    r"\[MemoryMaster (?:recall|session context[^\]]*|pre-compaction residual|residual)\]"
    r"|^#{1,3}\s*(?:Memory Context|Decisions you made earlier|Compiled User Profile)\b"
    r"|<!--\s*generated by MemoryMaster[^>]*-->"
    r"|(?:Stop[- ]hook feedback|hook_additional_context)"
    r"|mcp__memorymaster__|(?:generated (?:projection|observation)|compaction summary)",
    re.I | re.M,
)
_WRAPPER = re.compile(
    r"<(system-reminder|task-notification|task_briefing|persisted-output|local-command[^\s/>]*)\b[^>]*>"
    r"[\s\S]*?</\1\s*>", re.I,
)
_UNFINISHED_WRAPPER = re.compile(
    r"<(?:system-reminder|task-notification|task_briefing|persisted-output|local-command[^\s/>]*)\b", re.I,
)
_MEMORY_TOOLS = {"query_memory", "recall", "get_claim", "list_claims"}


def is_memory_tool(name: str | None) -> bool:
    normalized = str(name or "").lower()
    return "mcp__memorymaster__" in normalized or normalized in _MEMORY_TOOLS


def strip_self_observation(
    text: str, *, role: str, tool_name: str | None = None,
    metadata: MutableMapping[str, Any] | None = None,
) -> SanitizedTurn:
    """Retain attributable spans, with caller-owned structural state across turns.

    ``metadata['state']`` is mutable and may contain ``memory_tool_ids`` and
    ``tool_contaminated``. Callers must inspect tool records before dropping them.
    A genuine user turn clears tool contamination; injected or citation-bearing
    user records do not. Unbounded generated payloads conservatively hold a turn.
    """
    meta = metadata if metadata is not None else {}
    state = meta.setdefault("state", {})
    linked_ids = set(state.get("memory_tool_ids", ()))
    call_id = str(meta.get("tool_call_id") or "")
    memory_tool = is_memory_tool(tool_name) or bool(call_id and call_id in linked_ids)
    if memory_tool:
        if call_id:
            linked_ids.add(call_id)
        state["memory_tool_ids"] = sorted(linked_ids)
        state["tool_contaminated"] = True
    if role not in {"user", "assistant", "model"} or meta.get("injected") or meta.get("generated_session"):
        if meta.get("injected") or meta.get("generated_session") or _GENERATED.search(text) or _CITATION.search(text):
            state["tool_contaminated"] = True
        return SanitizedTurn("", exclusion_reasons=("structural_context",), contaminated=True)
    if memory_tool:
        return SanitizedTurn("", exclusion_reasons=("memory_tool",), contaminated=True)
    removed: list[tuple[int, int]] = []
    for match in _WRAPPER.finditer(text):
        # Persisted outputs are never followed; even an unmarked pointer may be
        # recalled content whose provenance was erased by the export.
        removed.append(match.span())
    spans: list[SourceSpan] = []
    position = 0
    for start, end in removed:
        if position < start:
            spans.append(SourceSpan(position, start, text[position:start]))
        position = end
    if position < len(text):
        spans.append(SourceSpan(position, len(text), text[position:]))
    remaining = "\n".join(span.text for span in spans)
    if _CITATION.search(remaining):
        state["tool_contaminated"] = True
        return SanitizedTurn("", exclusion_reasons=("memory_citation",), contaminated=True)
    if _GENERATED.search(remaining) or _UNFINISHED_WRAPPER.search(remaining):
        state["tool_contaminated"] = True
        return SanitizedTurn("", exclusion_reasons=("generated_memory",), contaminated=True)
    authored = remaining.strip()
    if removed and not authored:
        state["tool_contaminated"] = True
    if role == "user" and authored:
        state["tool_contaminated"] = False
        state["memory_tool_ids"] = []
    elif role in {"assistant", "model"} and state.get("tool_contaminated"):
        return SanitizedTurn("", exclusion_reasons=("tool_echo",), contaminated=True)
    return SanitizedTurn(
        authored, tuple(span for span in spans if span.text.strip()),
        ("injected_block",) if removed else (), bool(removed),
    )
