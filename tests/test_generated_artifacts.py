import pytest

from memorymaster.core.generated_artifacts import (
    GENERATED_CLOSER, GENERATED_OPENER, strip_generated_spans,
)


@pytest.mark.parametrize("opener", [GENERATED_OPENER, "<!-- GENERATED BY memorymaster ; rebuild instead of editing -->"])
def test_mixed_generated_spans_keep_original_offsets(opener):
    raw = f"Authored prefix.\n{opener}\nmm-12345678 recalled\n{GENERATED_CLOSER}\nAuthored suffix."
    clean = strip_generated_spans(raw)
    assert [span.text.strip() for span in clean.spans] == ["Authored prefix.", "Authored suffix."]
    assert all(raw[span.start:span.end] == span.text for span in clean.spans)
    assert "recalled" not in clean.text


def test_nested_repeated_and_unclosed_markers_quarantine_only_generated_ranges():
    raw = f"prefix{GENERATED_OPENER}outer{GENERATED_OPENER}inner{GENERATED_CLOSER}outer{GENERATED_CLOSER}suffix{GENERATED_OPENER}unclosed"
    clean = strip_generated_spans(raw)
    assert [span.text for span in clean.spans] == ["prefix", "suffix"]
    assert strip_generated_spans("\ufeff" + GENERATED_OPENER + "generated").text.strip("\ufeff \n") == ""
