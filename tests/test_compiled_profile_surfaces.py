from __future__ import annotations

import importlib.util
import io
import json
import subprocess
import sys
from pathlib import Path

import pytest


ROOT = Path(__file__).resolve().parents[1]
HOOK = ROOT / "memorymaster" / "config_templates" / "hooks" / "memorymaster-session-start.py"


def _hook_module():
    spec = importlib.util.spec_from_file_location("compiled_profile_session_hook", HOOK)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_session_start_no_longer_injects_wiki_activity_or_profile(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    # T-1944 (audit D3): the 24h activity line, wiki articles and compiled user profile are
    # dropped from SessionStart; the events table and a valid profile file must not leak back.
    import sqlite3

    module = _hook_module()
    db = tmp_path / "memory.db"
    with sqlite3.connect(db) as conn:
        conn.execute("CREATE TABLE claims(id INTEGER PRIMARY KEY, text TEXT, claim_type TEXT, status TEXT, "
                     "created_at TEXT, scope TEXT)")
        conn.execute("INSERT INTO claims VALUES(1, 'A complete claim.', 'fact', 'confirmed', '2026-10-29', "
                     "'project:fixture')")
        conn.execute("CREATE TABLE events(event_type TEXT, created_at TEXT)")
        conn.execute("INSERT INTO events VALUES('ingest', '2999-01-01T00:00:00+00:00')")
    profile = tmp_path / "user.md"
    profile.write_text("<!-- generated by MemoryMaster; rebuild instead of editing -->\nprofile fact\n",
                       encoding="utf-8")
    monkeypatch.setattr(module, "DB_PATH", db)
    monkeypatch.setattr(module, "_derive_scope", lambda: "project:fixture")
    monkeypatch.setattr(module, "_jev_session_active", lambda: False)
    monkeypatch.setattr(module, "_log", lambda *_a, **_k: None)
    monkeypatch.setattr(sys, "stdin", io.StringIO("{}"))
    with pytest.raises(SystemExit) as stopped:
        module.main()

    context = json.loads(capsys.readouterr().out)["hookSpecificOutput"]["additionalContext"]
    assert stopped.value.code == 0
    assert "A complete claim." in context
    for gone in ("Last 24h activity", "wiki articles", "compiled user profile", "profile fact"):
        assert gone not in context
    for helper in ("_query_last_cycle_summary", "_load_recent_wiki_articles", "_load_compiled_profile"):
        assert not hasattr(module, helper)


def test_profile_module_cli_status_and_help(tmp_path: Path) -> None:
    db = tmp_path / "profile.db"
    help_run = subprocess.run(
        [sys.executable, "-m", "memorymaster.profile", "--help"],
        capture_output=True,
        text=True,
        encoding="utf-8",
        timeout=20,
    )
    status_run = subprocess.run(
        [sys.executable, "-m", "memorymaster.profile", "status", "--db", str(db)],
        capture_output=True,
        text=True,
        encoding="utf-8",
        timeout=20,
    )

    assert help_run.returncode == 0
    assert "compiled user profile" in help_run.stdout.lower()
    assert status_run.returncode == 0
    payload = json.loads(status_run.stdout)
    assert payload == {"active_run": None, "facts": 0, "latest_completed_run": None}


def test_session_start_drops_whole_claims_instead_of_cutting_them() -> None:
    # Fleet T-0797 capped SessionStart in the installed copy only; `setup` overwrites that copy
    # with this template, so the cap must live here. T-1944: a claim is shown whole or not at all.
    module = _hook_module()
    claims = [{"id": i, "type": "fact", "status": "confirmed",
               "text": f"Claim number {i} " + ("word " * 80).strip() + " ends here."} for i in range(5)]

    context = module._format_context("project:test", claims, 3)

    assert len(context) <= module.MAX_CONTEXT_CHARS <= 1_500
    shown = [line for line in context.splitlines() if line.startswith("  - #")]
    assert 1 <= len(shown) < len(claims)
    for line in shown:
        assert line.endswith("ends here."), line
    assert "…" not in context
    assert context.startswith("[MemoryMaster session context") and "query_memory" in context.splitlines()[-1]
    assert "WARNING: 3 candidate" in context
    short = [{"id": i, "type": "fact", "status": "confirmed", "text": f"Short claim {i}."} for i in range(5)]
    assert module._format_context("project:test", short, 0).count("  - #") == 5


