from __future__ import annotations

import json

import pytest

from memorymaster.dreaming.capture import capture_transcript, parse_transcript_lines
from memorymaster.dreaming.ledger import DreamLedger
from memorymaster.dreaming.self_observation import strip_self_observation


def test_balanced_generated_citation_does_not_poison_authored_spans():
    from memorymaster.core.generated_artifacts import GENERATED_CLOSER, GENERATED_OPENER
    text = f"Choose WAL.\n{GENERATED_OPENER}\nmm-12345678 old memory\n{GENERATED_CLOSER}\nUse transactions."
    clean = strip_self_observation(text, role="assistant")
    assert "Choose WAL." in clean.text and "Use transactions." in clean.text
    assert "old memory" not in clean.text
    assert all(text[span.start:span.end] == span.text for span in clean.spans)


@pytest.mark.parametrize("text", [
    "[MemoryMaster recall]\nPrior claim",
    "# Memory Context\nPrior claim",
    "[MemoryMaster session context project:x]\nprofile",
    "[MemoryMaster residual] Context was just compacted.\nprior fact",
    "[MemoryMaster pre-compaction residual]\nprior fact",
    "# Decisions you made earlier\nprior decision",
    "<!-- generated by MemoryMaster; rebuild instead of editing -->\n# Compiled User Profile",
    "Stop-hook feedback: prior fact",
    "Quoted claim table | mm-1234abcdef-2 | prior fact",
    "hook_additional_context: prior fact",
    "<persisted-output>Read prior facts from /tmp/result</persisted-output>",
    "<task_briefing>Prior memory</task_briefing>",
    "<system-reminder>Prior memory</system-reminder>",
    "<task-notification>Prior memory</task-notification>",
    "<local-command-stdout>Prior memory</local-command-stdout>",
])
@pytest.mark.parametrize("role", ["user", "assistant"])
def test_generated_context_cannot_become_source(text, role):
    clean = strip_self_observation(text, role=role)
    assert not clean.text
    assert clean.contaminated
    row = {"type": role, "message": {"role": role, "content": text}}
    assert parse_transcript_lines(json.dumps(row), "claude") == []


def test_disjoint_authored_spans_keep_original_offsets():
    text = "Use SQLite.\n<system-reminder>mm-12345678 remembered</system-reminder>\nKeep WAL."
    clean = strip_self_observation(text, role="user")
    assert clean.text == "Use SQLite.\n\n\nKeep WAL."
    assert len(clean.spans) == 2
    assert all(text[span.start:span.end] == span.text for span in clean.spans)


@pytest.mark.parametrize("provider", ["claude", "codex"])
def test_tool_linkage_blocks_echo_until_genuine_user(provider):
    def message(role, text):
        if provider == "codex":
            return {"type": "response_item", "payload": {"type": "message", "role": role, "content": text}}
        return {"type": role, "message": {"role": role, "content": text}}

    call = {"type": "tool_use", "id": "recall-1", "name": "mcp__memorymaster__query_memory"}
    if provider == "codex":
        tool_call = {"type": "response_item", "payload": {"type": "function_call", "call_id": "recall-1", "name": call["name"]}}
    else:
        tool_call = {"type": "assistant", "message": {"role": "assistant", "content": [call]}}
    rows = [tool_call, message("assistant", "An unmarked echo of retrieved facts."),
            message("user", "[MemoryMaster recall]\ninjected"),
            message("assistant", "Still echoing recalled facts."),
            message("user", "Choose WAL for this new database."),
            message("assistant", "WAL selected for the new database.")]
    messages = parse_transcript_lines("\n".join(map(json.dumps, rows)), provider)
    assert [m.text for m in messages] == ["Choose WAL for this new database.", "WAL selected for the new database."]


def test_live_capture_keeps_contamination_across_incremental_reads(tmp_path):
    transcript = tmp_path / "session.jsonl"
    ledger = DreamLedger(tmp_path / "capture.db")
    transcript.write_text(json.dumps({"type": "assistant", "message": {"role": "assistant", "content": [
        {"type": "tool_use", "id": "r1", "name": "mcp__memorymaster__recall"},
    ]}}) + "\n", encoding="utf-8")
    args = dict(provider="claude", session_id="fixture", cwd=str(tmp_path), ledger=ledger)
    assert capture_transcript(transcript, **args)["reason"] == "no_conversation"
    with transcript.open("a", encoding="utf-8") as handle:
        handle.write(json.dumps({"type": "assistant", "message": {"role": "assistant", "content": "Unmarked echo."}}) + "\n")
    assert capture_transcript(transcript, **args)["reason"] == "no_conversation"


def test_separated_authored_spans_are_distinct_persisted_extractor_evidence(tmp_path):
    from memorymaster.core.generated_artifacts import GENERATED_CLOSER, GENERATED_OPENER
    from memorymaster.dreaming.worker import DreamConfig, DreamWorker

    raw = "Use " + GENERATED_OPENER + "injected gap" + GENERATED_CLOSER + "SQLite for production."
    row = {"role": "assistant", "uuid": "original-turn", "content": raw}
    messages = parse_transcript_lines(json.dumps(row), "claude")
    assert [message.text for message in messages] == ["Use", "SQLite for production."]
    assert len({message.message_id for message in messages}) == 2
    transcript = tmp_path / "span-session.jsonl"
    transcript.write_text(json.dumps(row) + "\n", encoding="utf-8")
    ledger = DreamLedger(tmp_path / "spans.db")
    result = capture_transcript(transcript, provider="claude", session_id="spans", cwd=str(tmp_path),
                                ledger=ledger, live_workspace=True)
    persisted = ledger.get_capture(result["capture_id"])["messages"]
    worker = object.__new__(DreamWorker)
    worker.config = DreamConfig()
    assert [message["text"] for message in worker._bounded_messages(persisted)] == ["Use", "SQLite for production."]
